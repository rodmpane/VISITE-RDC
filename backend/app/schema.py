"""Initial schema. On a deployed system use reviewed migrations for changes."""
from .db import connection, is_sqlite


TABLES = """
CREATE TABLE IF NOT EXISTS provinces (
 id TEXT PRIMARY KEY, nom TEXT NOT NULL, chef_lieu TEXT
);
CREATE TABLE IF NOT EXISTS lieux (
 id TEXT PRIMARY KEY, nom TEXT NOT NULL,
 province_id TEXT REFERENCES provinces(id),
 type TEXT NOT NULL CHECK(type IN ('ville','frontiere','international')),
 latitude DOUBLE PRECISION, longitude DOUBLE PRECISION
);
CREATE TABLE IF NOT EXISTS points (
 id TEXT PRIMARY KEY, lieu_id TEXT NOT NULL REFERENCES lieux(id),
 type TEXT NOT NULL CHECK(type IN ('aeroport','aerodrome','port','gare_train','gare_routiere','arret')),
 nom TEXT NOT NULL, code TEXT, latitude DOUBLE PRECISION, longitude DOUBLE PRECISION,
 verifie INTEGER NOT NULL DEFAULT 0 CHECK(verifie IN (0,1))
);
CREATE TABLE IF NOT EXISTS operateurs (
 id TEXT PRIMARY KEY, nom TEXT NOT NULL, type TEXT, note TEXT
);
CREATE TABLE IF NOT EXISTS liaisons (
 id {identity},
 mode TEXT NOT NULL CHECK(mode IN ('avion','fleuve','lac','bac','train','bus','voiture','moto')),
 depart_id TEXT NOT NULL REFERENCES lieux(id),
 arrivee_id TEXT NOT NULL REFERENCES lieux(id),
 distance_km INTEGER, duree_h DOUBLE PRECISION,
 prix_min_usd DOUBLE PRECISION, prix_max_usd DOUBLE PRECISION,
 etat_route TEXT, operateur TEXT, frequence TEXT, note TEXT,
 statut TEXT NOT NULL DEFAULT 'a_verifier' CHECK(statut IN ('ok','a_verifier','suspendu')),
 publie INTEGER NOT NULL DEFAULT 0 CHECK(publie IN (0,1)),
 verifie_le TEXT, source_info TEXT,
 source_hash TEXT UNIQUE,
 CHECK(depart_id <> arrivee_id),
 CHECK(distance_km IS NULL OR distance_km >= 0),
 CHECK(duree_h IS NULL OR duree_h > 0),
 CHECK(prix_min_usd IS NULL OR prix_min_usd >= 0),
 CHECK(prix_max_usd IS NULL OR prix_max_usd >= prix_min_usd)
);
CREATE INDEX IF NOT EXISTS idx_liaisons_depart ON liaisons(depart_id);
CREATE INDEX IF NOT EXISTS idx_liaisons_arrivee ON liaisons(arrivee_id);
CREATE INDEX IF NOT EXISTS idx_liaisons_pub ON liaisons(publie,statut);
"""


def init_schema():
    identity = "INTEGER PRIMARY KEY AUTOINCREMENT" if is_sqlite() else "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    ddl = TABLES.format(identity=identity)
    with connection() as conn:
        for statement in ddl.split(";"):
            if statement.strip():
                conn.execute(statement)
